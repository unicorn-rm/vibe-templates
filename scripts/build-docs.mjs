#!/usr/bin/env node
// Regenerates per-template docs (README.md, README.ru.md, DESIGN.md, AGENTS.md)
// and the catalog tables in the root READMEs from templates.json.
// Usage: node scripts/build-docs.mjs
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const ROOT = new URL("..", import.meta.url).pathname;
const REPO = "unicorn-rm/vibe-templates";
const PAGES = "https://unicorn-rm.github.io/vibe-templates";
const { templates } = JSON.parse(readFileSync(join(ROOT, "templates.json"), "utf8"));

const fontLink = (f) => `[${f}](https://fonts.google.com/specimen/${f.replace(/ /g, "+")})`;
const list = (a) => a.map((x) => `- ${x}`).join("\n");
const num = (t) => t.id.slice(0, 2);

const prompt = {
  en: (t) => `You are adapting the "${t.id}" template from vibe-templates.
Read DESIGN.md and AGENTS.md in this folder first and keep every rule in DESIGN.md.
My project: <what it is, who it is for, 2–3 sentences>.
Replace all copy and data in ${Object.keys(t.files)[0]} with content for my project, in English and Russian.
Keep the layout, the fonts, the signature block and the motion. You may change the palette tokens only if you keep the same number of accents and contrast of at least 4.5:1 for body text.
Do not add new dependencies. When done, list what you changed.`,
  ru: (t) => `Ты адаптируешь шаблон "${t.id}" из vibe-templates.
Сначала прочитай DESIGN.md и AGENTS.md в этой папке и соблюдай все правила из DESIGN.md.
Мой проект: <что это, для кого, 2–3 предложения>.
Замени весь текст и данные в ${Object.keys(t.files)[0]} на контент моего проекта, на английском и русском.
Сохрани сетку, шрифты, фирменный блок и анимации. Палитру можно менять только в токенах, сохранив число акцентов и контраст текста не ниже 4.5:1.
Не добавляй новые зависимости. В конце перечисли, что изменил.`,
};

function readme(t, lang) {
  const en = lang === "en";
  const other = en ? "[Русская версия](README.ru.md)" : "[English version](README.md)";
  return `<!-- generated by scripts/build-docs.mjs from templates.json — edit there -->
# ${num(t)} · ${t.name} — ${t.kind[lang]}

${other} · [${en ? "Live demo" : "Демо"}](${PAGES}/${t.id}/) · [${en ? "All templates" : "Все шаблоны"}](../../${en ? "README.md" : "README.ru.md"})

![${t.name} preview](preview.png)

- **${en ? "Style" : "Стиль"}:** ${t.style[lang]}
- **${en ? "Stack" : "Стек"}:** ${t.stack.join(" · ")}
- **${en ? "Fonts" : "Шрифты"}:** ${t.fonts.map(fontLink).join(", ")} (${en ? "Latin + Cyrillic" : "латиница + кириллица"})
- **${en ? "Signature block" : "Фирменный блок"}:** ${t.signature[lang]}

## ${en ? "Run it" : "Запуск"}

\`\`\`bash
${t.run.join("\n")}
\`\`\`

## ${en ? "Blocks inside" : "Какие блоки внутри"}

${list(t.blocks)}

## ${en ? "Where things live" : "Где что лежит"}

| ${en ? "File" : "Файл"} | ${en ? "What to edit there" : "Что там менять"} |
|---|---|
${Object.entries(t.files).map(([f, d]) => `| \`${f}\` | ${d} |`).join("\n")}

${en ? "The page speaks English by default. Russian: the language button, or" : "По умолчанию страница на английском. Русский — кнопкой языка или"} \`?lang=ru\`.

## ${en ? "Make it yours with AI" : "Переделать под себя с ИИ"}

${en ? "Open this folder in Claude Code, Cursor, Copilot or any coding agent and paste:" : "Откройте эту папку в Claude Code, Cursor, Copilot или другом агенте и вставьте:"}

\`\`\`text
${prompt[lang](t)}
\`\`\`

${en ? "Design rules the agent must keep are in" : "Правила дизайна, которые агент должен сохранить, — в"} [DESIGN.md](DESIGN.md).

## ${en ? "License" : "Лицензия"}

MIT — ${en ? "use it for anything, credit appreciated." : "используйте как угодно, ссылка на репозиторий приветствуется."} ${t.id === "14-fine-dining" ? (en ? "Demo photos are from [Unsplash](https://unsplash.com/license) and hot-linked; replace them with your own." : "Демо-фото с [Unsplash](https://unsplash.com/license), подключены ссылками; замените своими.") : ""}
`;
}

function design(t) {
  return `<!-- generated by scripts/build-docs.mjs from templates.json — edit there -->
# DESIGN — ${num(t)} · ${t.name}

> ${t.idea.en}
>
> ${t.idea.ru}

## Tokens

| Token | Value |
|---|---|
${Object.entries(t.palette).map(([k, v]) => `| \`${k}\` | \`${v}\` ![](https://placehold.co/14x14/${v.slice(1)}/${v.slice(1)}.png) |`).join("\n")}

Fonts: ${t.fonts.map(fontLink).join(" + ")}. All support Cyrillic — keep that if you swap them.

## Signature block

${t.signature.en}

## Rules (keep these)

${list(t.rules.en)}

## Правила (сохранять)

${list(t.rules.ru)}

## Blocks

${list(t.blocks)}
`;
}

function agents(t) {
  return `<!-- generated by scripts/build-docs.mjs from templates.json — edit there -->
# AGENTS.md — ${t.id}

Instructions for AI coding agents working in this folder.

## Context
- Template: **${t.name}**, ${t.kind.en.toLowerCase()}, style "${t.style.en}".
- Stack: ${t.stack.join(", ")}. Do not add dependencies unless the user asks.
- The design contract is in \`DESIGN.md\`. Read it before changing anything visual.

## Files
${Object.entries(t.files).map(([f, d]) => `- \`${f}\` — ${d}`).join("\n")}

## How to run
${t.run.map((r) => `- \`${r}\``).join("\n")}

## Rules
- Content changes go to the content file, not into markup or components.
- Every user-facing string exists in **en** and **ru**. English is the default; \`?lang=ru\` and the language button switch it.
- Colors, fonts, radii and spacing are tokens. Change tokens, not individual elements.
- Keep the signature block: ${t.signature.en}.
- Keep accessibility: semantic headings, visible focus, alt text, \`prefers-reduced-motion\` support, body text contrast ≥ 4.5:1.
- Keep it static: no backend, no booking or payment flows.
${list(t.rules.en)}

## Done means
- The page builds/opens without console errors.
- Both languages render with no missing strings.
- Layout works from 360 px to 1920 px wide.
`;
}

function catalog(lang) {
  const en = lang === "en";
  const head = en
    ? "| # | Template | Style | Stack | Signature block |\n|---|---|---|---|---|"
    : "| # | Шаблон | Стиль | Стек | Фирменный блок |\n|---|---|---|---|---|";
  const rows = templates.map((t) => {
    const ready = t.status === "ready";
    const title = ready ? `[**${t.name}** · ${t.kind[lang]}](templates/${t.id}/${en ? "README.md" : "README.ru.md"})` : `${t.kind[lang]} <sub>${en ? "soon" : "скоро"}</sub>`;
    return `| ${num(t)} | ${title} | ${t.style[lang]} | ${t.stack.join(", ")} | ${ready ? t.signature[lang] : "—"} |`;
  });
  return `${head}\n${rows.join("\n")}`;
}

function gallery(lang) {
  const ready = templates.filter((t) => t.status === "ready");
  const cells = ready.map((t) =>
    `<td width="50%" valign="top"><a href="templates/${t.id}/${lang === "en" ? "README.md" : "README.ru.md"}"><img src="templates/${t.id}/preview.png" alt="${t.name}" /></a><br /><b>${num(t)} · ${t.name}</b> — ${t.style[lang]}<br /><sub>${t.stack.join(" · ")} · <a href="${PAGES}/${t.id}/">demo</a></sub></td>`);
  const rows = [];
  for (let i = 0; i < cells.length; i += 2) rows.push(`<tr>\n${cells.slice(i, i + 2).join("\n")}\n</tr>`);
  return `<table>\n${rows.join("\n")}\n</table>`;
}

function inject(file, marker, content) {
  const p = join(ROOT, file);
  const src = readFileSync(p, "utf8");
  const re = new RegExp(`(<!-- ${marker}:start -->)[\\s\\S]*?(<!-- ${marker}:end -->)`);
  writeFileSync(p, src.replace(re, `$1\n${content}\n$2`));
}

for (const t of templates.filter((x) => x.status === "ready")) {
  const dir = join(ROOT, "templates", t.id);
  if (!existsSync(dir)) { console.warn(`skip ${t.id}: folder missing`); continue; }
  writeFileSync(join(dir, "README.md"), readme(t, "en"));
  writeFileSync(join(dir, "README.ru.md"), readme(t, "ru"));
  writeFileSync(join(dir, "DESIGN.md"), design(t));
  writeFileSync(join(dir, "AGENTS.md"), agents(t));
}
for (const [file, lang] of [["README.md", "en"], ["README.ru.md", "ru"]]) {
  if (!existsSync(join(ROOT, file))) continue;
  inject(file, "catalog", catalog(lang));
  inject(file, "gallery", gallery(lang));
}
console.log(`docs: ${templates.filter((t) => t.status === "ready").length} ready / ${templates.length} total · repo ${REPO}`);
